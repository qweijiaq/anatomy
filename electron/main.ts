/**
 * Where the app's own files live.
 *
 * The main process is bundled to CJS, where `__filename` is defined and
 * `import.meta.url` is rewritten to an empty object by esbuild. Falling back to the
 * ESM form keeps `tsx electron/main.ts` working during development.
 */
declare const __filename: string | undefined
const here =
  typeof __filename === 'string' ? path.dirname(__filename) : path.dirname(fileURLToPath(import.meta.url))

let window: BrowserWindow | null = null

/**
 * The Dock icon, from `build/icon.icns`.
 *
 * Without one macOS shows the generic placeholder — a blank rounded square — which
 * is indistinguishable from a crashed app in the Dock. The file is generated by
 * `scripts/build-icon.mjs` and committed, so a checkout runs without a build step.
 */
function setDockIcon(): void {
  if (process.platform !== 'darwin' || app.dock === undefined) return
  try {
    const icon = nativeImage.createFromPath(path.join(here, '..', 'build', 'icon-1024.png'))
    if (!icon.isEmpty()) app.dock.setIcon(icon)
  } catch {
    // A missing icon is cosmetic; the window still has to open.
  }
}

function createWindow(): void {
  window = new BrowserWindow({
    width: 1180,
    height: 820,
    minWidth: 900,
    minHeight: 640,
    title: 'anatomy',
    titleBarStyle: process.platform === 'darwin' ? 'hiddenInset' : 'default',
    backgroundColor: '#faf9f7',
    webPreferences: {
      preload: path.join(here, 'preload.cjs'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false,
    },
  })

  const devUrl = process.env['ANA_DEV_SERVER']
  if (typeof devUrl === 'string' && devUrl !== '') {
    void window.loadURL(devUrl)
  } else {
    void window.loadFile(path.join(here, '../dist-renderer/index.html'))
  }

  // Content Security Policy for the dev server, which needs a websocket for hot
  // reload. The packaged app gets its policy from a `<meta>` tag injected at build
  // time by `vite.config.ts`: measured on the built app, this hook fires for a
  // `file://` document but the policy is not enforced, so relying on it alone left
  // the packaged renderer with no CSP at all while this comment claimed otherwise.
  const isDev = typeof devUrl === 'string' && devUrl !== ''
  window.webContents.session.webRequest.onHeadersReceived((details, callback) => {
    const policy = isDev
      ? "default-src 'self'; script-src 'self' 'unsafe-inline' 'unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self' ws: http://localhost:*"
      : "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; connect-src 'self'"
    callback({ responseHeaders: { ...details.responseHeaders, 'Content-Security-Policy': [policy] } })
  })

  // An external link opens in the user's browser, never inside the app: the
  // renderer shows provider documentation and repository URLs.
  window.webContents.setWindowOpenHandler(({ url }) => {
    void shell.openExternal(url)
    return { action: 'deny' }
  })
}

// A user agent model id makes the Dock label and notification identity the app's
// own rather than "Electron".
app.setName('anatomy')
if (process.platform === 'win32') app.setAppUserModelId('ai.anatomy.app')

void app.whenReady().then(() => {
  setDockIcon()
  createWindow()
  app.on('activate', () => {
    if (BrowserWindow.getAllWindows().length === 0) createWindow()
  })
})

app.on('window-all-closed', () => {
  if (process.platform !== 'darwin') app.quit()
})

