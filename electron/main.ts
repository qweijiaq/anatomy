/**
 * One cheap round-trip that proves the key, the endpoint and the model name all
 * agree. It asks for a tiny JSON object so a provider that ignores
 * `response_format` is still caught.
 */
ipcMain.handle('settings:test', async () => {
  const config = activeModelConfig()
  if (config.apiKey === '') {
    return { ok: false, message: '还没有配置 API Key。' }
  }
  const client = createModelClient({
    model: config.model,
    baseUrl: config.baseUrl,
    apiKey: config.apiKey,
    protocol: config.protocol as Protocol,
    maxRetries: 0,
    timeoutMs: 30_000,
  })
  try {
    const started = Date.now()
    const reply = await client.complete({
      system: 'Reply with the JSON object {"ok": true} and nothing else.',
      user: 'ping',
      schema: { type: 'object' },
    })
    return {
      ok: true,
      message: `连接成功，用时 ${Date.now() - started} ms。`,
      usage: reply.usage,
    }
  } catch (error) {
    const message =
      error instanceof MissingCredentialsError
        ? '还没有配置 API Key。'
        : error instanceof Error
          ? error.message
          : String(error)
    return { ok: false, message }
  }
})

// --- zero-token scan --------------------------------------------------------
//
// The CLI has had `ana scan` from the start — no model, no key, tells you where to
// look. The window did not, so the only way to look at a repository from the app was
// the full analysis, which spends tokens. That is the wrong shape for the first
// thing a person does with an unfamiliar repository.
//
// Scans overwrite one scratch directory rather than accumulating runs: a scan is a
// glance, not a record, and twenty glances should not leave twenty directories. The
// full analysis is what gets a durable run id.

ipcMain.handle('analysis:scan', async (_event, request: unknown) => {
  const repo = typeof (request as { repo?: unknown })?.repo === 'string' ? (request as { repo: string }).repo : ''
  if (repo.trim() === '') return { ok: false, message: '需要一个仓库地址或本地路径。' }
  const top = typeof (request as { top?: unknown })?.top === 'number' ? (request as { top: number }).top : 12
  try {
    const summary = await runScan(repo, {
      out: path.resolve(process.cwd(), '.ana', 'scratch'),
      topK: top,
    })
    return {
      ok: true,
      runId: summary.runId,
      candidates: summary.candidates.map((candidate) => ({
        path: candidate.path,
        line: candidate.line,
        kind: candidate.kind,
        score: candidate.score,
        matched: candidate.matched,
      })),
    }
  } catch (error) {
    return { ok: false, message: error instanceof Error ? error.message : String(error) }
  }
})

// --- analysis ---------------------------------------------------------------

type Progress = { phase: string; detail?: string; done?: number; total?: number }

ipcMain.handle('analysis:run', async (event, payload: unknown) => {
  const request = payload as { repo?: unknown; top?: unknown; lang?: unknown }
  const repo = typeof request?.repo === 'string' ? request.repo.trim() : ''
  if (repo === '') return { ok: false, message: '请先填一个仓库地址。' }

  const config = activeModelConfig()
  if (config.apiKey === '') return { ok: false, message: '还没有配置 API Key。' }
  const settings = getSettingsView()
  rememberRepo(repo)

  const send = (progress: Progress): void => {
    if (!event.sender.isDestroyed()) event.sender.send('analysis:progress', progress)
  }

  try {
    // No phase is announced here. `runAnalyze` emits its own — acquire, judge, rank,
    // synthesise — and announcing "analyse" first made the progress bar move backwards
    // into "acquire" a moment later. Observed by driving the real window: the sequence
    // was acquire, analyse, acquire, judge… with the second acquire arriving after
    // the label had already moved on.
    const client = createModelClient({
      model: config.model,
      baseUrl: config.baseUrl,
      apiKey: config.apiKey,
      protocol: config.protocol as Protocol,
      maxRetries: 2,
      timeoutMs: 120_000,
    })
    const result = await runAnalyze(repo, {
      client,
      top: typeof request?.top === 'number' ? request.top : settings.topN,
      reportPoints: settings.reportPoints,
      lang: request?.lang === 'en' ? 'en' : 'zh',
      // Forward the fine-grained stages: judging alone is one model call per
      // candidate, and a spinner that never moves is indistinguishable from a hang.
      onStage: (stage) =>
        send({
          phase: stage.stage,
          detail: stage.detail,
          done: stage.done,
          total: stage.total,
        }),
    })
    send({ phase: 'done' })

    // The run finished, but "finished" is not "worked". A provider that rejects every
    // request — a revoked key, a model it does not serve — produces a report with no
    // points, and this handler used to return ok with it: the window showed a quiet
    // empty report for what was really a configuration failure. The CLI had already
    // learned this; `describeRunFailure` is the one place both ask.
    const failure = describeRunFailure(result)
    if (failure !== '') return { ok: false, message: failure }

    const markdown = await runReport(result.runId)
    return { ok: true, runId: result.runId, reportPath: result.reportPath, markdown }
  } catch (error) {
    return { ok: false, message: error instanceof Error ? error.message : String(error) }
  }
})

// --- report history ---------------------------------------------------------
//
// Every run leaves a directory behind, but until now nothing in the UI could reach
// an older one: a report was visible exactly until the next run replaced it. The
// list below is read off disk on every call rather than cached, because a run that
// finished one second ago must appear without a restart.

type ReportSummary = {
  runId: string
  source: string
  startedAt: string
  /** How many points the report's top list ended up with. */
  points: number
  title: string
}

ipcMain.handle('runs:list', async () => {
  // The list is `listRuns`'s answer, not a second opinion. Until now the window and
  // `ana runs` each decided for themselves what "has a report" means — the window
  // required `synthesis` and `validation`, the CLI required `synthesis` and a points
  // array — so a run could be listed in one and invisible in the other, and the two
  // copies had no reason to stay in step.
  const baseDir = path.resolve(process.cwd(), DEFAULT_RUNS_DIR)
  const stored = await listRuns({ baseDir })

  const runs: ReportSummary[] = []
  for (const run of stored) {
    // A `scan` run completes too, and has no report. The question this list asks is
    // "can I read a report here", so that is the question it must actually check.
    if (!run.hasReport) continue
    runs.push({
      runId: run.runId,
      source: run.source,
      startedAt: run.startedAt,
      points: run.points ?? 0,
      // The best one-line label available without a network call: the repo's last
      // path segment, falling back to the run id.
      title: (() => {
        const cleaned = run.source.replace(/[/\\]+$/, '')
        const segment = cleaned.slice(cleaned.lastIndexOf('/') + 1)
        return segment === '' ? run.runId : segment
      })(),
    })
  }
  return { ok: true, runs }
})

/**
 * Show the report file in the file manager.
 *
 * The report is not only what the window renders — it is a file at
 * `.ana/runs/<id>/report.md`, and someone who reads it usually wants it next to the
 * code it talks about. Opening the folder is the one action that makes that easy
 * without inventing an editor integration, which would be platform- and
 * editor-specific for no extra benefit.
 */
ipcMain.handle('report:reveal', async (_event, runId: unknown) => {
  if (typeof runId !== 'string' || runId === '') return { ok: false, message: '缺少 run id。' }
  const file = path.resolve(process.cwd(), '.ana', 'runs', path.basename(runId), 'report.md')
  try {
    await stat(file)
  } catch {
    return { ok: false, message: '这份报告没有落成文件，先跑一次分析。' }
  }
  shell.showItemInFolder(file)
  return { ok: true, path: file }
})

ipcMain.handle('report:read', async (_event, runId: unknown) => {
  if (typeof runId !== 'string' || runId === '') return { ok: false, message: '缺少 run id。' }
  try {
    return { ok: true, markdown: await runReport(runId) }
  } catch (error) {
    // `NoSuchRunError` says which artifact is missing, in the CLI's words. Here that
    // reads as a stack-trace fragment, and the one case a person can hit — a scan
    // record opened as a report — has a plain explanation.
    if (error instanceof NoSuchRunError) {
      return { ok: false, message: `这个目录里只有扫描结果，没有报告（${runId}）。` }
    }
    return { ok: false, message: error instanceof Error ? error.message : String(error) }
  }
})

// --- application surveys ----------------------------------------------------
//
// `ana inspect-app` does the slow part — minutes of REA work over a bundle — and
// leaves a `survey.json` beside the evidence file. The window only reads those.
// Rendering on demand instead of analysing here is deliberate: a six-minute
// analysis behind a button needs cancellation, progress and a kill switch, and none
// of that belongs in a viewer.

ipcMain.handle('surveys:list', async () => {
  const baseDir = path.resolve(process.cwd(), '.ana', 'apps')
  let entries: string[]
  try {
    entries = await readdir(baseDir)
  } catch {
    return { ok: true, surveys: [] }
  }

  const surveys: unknown[] = []
  for (const entry of entries) {
    const file = path.join(baseDir, entry, 'survey.json')
    try {
      const parsed: unknown = JSON.parse(await readFile(file, 'utf8'))
      if (typeof parsed === 'object' && parsed !== null) {
        // The directory name is how a specific survey is asked for later.
        surveys.push({ ...(parsed as Record<string, unknown>), dirName: entry })
      }
    } catch {
      // A half-written survey is not a survey; skip it rather than fail the list.
    }
  }
  return { ok: true, surveys }
})

/**
 * `surveys:diff` — the boundary of one build against another.
 *
 * Both surveys are read from disk and diffed in the main process, then rendered to
 * the same markdown the CLI prints. One renderer, two front ends: a table that
 * looks different in the window than in `app-diff` would be two answers to one
 * question.
 */
ipcMain.handle('surveys:diff', async (_event, before: unknown, after: unknown) => {
  if (typeof before !== 'string' || typeof after !== 'string') {
    return { ok: false, message: '需要两个 survey 目录名。' }
  }
  const baseDir = path.resolve(process.cwd(), '.ana', 'apps')
  const load = async (name: string): Promise<AppSurvey | null> => {
    try {
      const raw = await readFile(path.join(baseDir, path.basename(name), 'survey.json'), 'utf8')
      return JSON.parse(raw) as AppSurvey
    } catch {
      return null
    }
  }
  const [a, b] = await Promise.all([load(before), load(after)])
  if (a === null || b === null) {
    return { ok: false, message: '有一份 survey 读不出来，可能已经被重新分析覆盖。' }
  }
  const diff = diffSurveys(a, b)
  if (isEmptyDiff(diff) && diff.comparable) {
    return { ok: true, markdown: `# ${b.name}\n\n两次分析的暴露面没有差异。\n` }
  }
  return { ok: true, markdown: renderAppDiff(diff) }
})

/**
 * Deleting one stored analysis from the window.
 *
 * Same rule as the CLI: an id, never a path, resolved under a known directory. The
 * view that shows a row is also the view that can remove it — a history nobody can
 * prune is a history that becomes a liability.
 */
ipcMain.handle('runs:forget', async (_event, kind: unknown, id: unknown) => {
  if (typeof id !== 'string' || (kind !== 'run' && kind !== 'app')) {
    return { ok: false, message: '需要 run id 和应用名。' }
  }
  try {
    const result = await forget(id, { target: kind })
    if ('missing' in result) return { ok: false, message: '这一份已经不在了。' }
    return { ok: true }
  } catch (error) {
    return { ok: false, message: error instanceof Error ? error.message : String(error) }
  }
})

// --- model discovery --------------------------------------------------------
//
// Every OpenAI-shaped endpoint answers `GET /models`, and most Anthropic-compatible
// gateways do too. Asking the provider beats a hard-coded list: the list in
// `providers.ts` is a starting point, not the truth about what a key can reach,
// and a person who just bought access to a new model should not have to type its
// exact id from memory.
//
// Failures are returned, not thrown: an endpoint that does not implement /models
// is common, and the field stays editable either way.

type ModelChoice = { id: string; ownedBy?: string }

ipcMain.handle('models:list', async () => {
  const config = activeModelConfig()
  if (config.apiKey === '') return { ok: false, message: '还没有配置 API Key。' }

  const base = config.baseUrl.replace(/\/+$/, '')
  // Anthropic's Messages API has its own listing route with its own shape; the
  // gateways this app ships for speak OpenAI even when they take Messages bodies.
  const url = `${base}/models`
  try {
    const response = await fetch(url, {
      method: 'GET',
      headers: {
        authorization: `Bearer ${config.apiKey}`,
        'x-api-key': config.apiKey,
        'anthropic-version': '2023-06-01',
      },
      signal: AbortSignal.timeout(15_000),
    })
    if (!response.ok) {
      return {
        ok: false,
        message: `这个端点没有返回模型列表（HTTP ${response.status}）。模型 ID 仍然可以手填。`,
      }
    }
    const body: unknown = await response.json()
    const raw = (body as { data?: unknown })?.data
    const items = Array.isArray(raw) ? raw : Array.isArray(body) ? body : []
    const models: ModelChoice[] = []
    for (const item of items) {
      const id = (item as { id?: unknown })?.id
      if (typeof id === 'string' && id !== '') {
        const ownedBy = (item as { owned_by?: unknown })?.owned_by
        models.push(typeof ownedBy === 'string' && ownedBy !== '' ? { id, ownedBy } : { id })
      }
    }
    models.sort((a, b) => a.id.localeCompare(b.id))
    return { ok: true, models }
  } catch (error) {
    return {
      ok: false,
      message: `拿不到模型列表：${error instanceof Error ? error.message : String(error)}。模型 ID 仍然可以手填。`,
    }
  }
})

// --- folder picker ----------------------------------------------------------
//
// The run field accepts a path or a URL, and typing a path by hand is where people
// mistype free text for a filesystem location. A native NSOpenPanel is the one
// dialog that *should* stay native: it is a system file browser that people already
// know, it has full disk-access and bookmark privileges, and no in-app list can
// reproduce it. Everything else in this app is hand-drawn; this is the exception
// because a reimplementation would be worse, not better.

ipcMain.handle('dialog:pickFolder', async (event) => {
  const window = BrowserWindow.fromWebContents(event.sender)
  const options: Electron.OpenDialogOptions = {
    title: '选择要拆解的仓库',
    properties: ['openDirectory', 'createDirectory', 'showHiddenFiles'],
    buttonLabel: '拆解',
  }
  const result = window === null ? await dialog.showOpenDialog(options) : await dialog.showOpenDialog(window, options)
  if (result.canceled || result.filePaths.length === 0) return { ok: false, canceled: true }
  return { ok: true, path: result.filePaths[0] }
})

