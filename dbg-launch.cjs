// Isolate the crash: create a window, load nothing, report what happens.
const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const log = (m) => fs.appendFileSync('/tmp/ana-dbg.log', new Date().toISOString() + ' ' + m + '\n')
log('main start, versions=' + process.versions.electron)
app.on('window-all-closed', () => { log('window-all-closed'); app.quit() })
app.whenReady().then(() => {
  log('ready')
  const win = new BrowserWindow({ width: 900, height: 700, show: false })
  log('window created')
  win.loadFile('dist-renderer/index.html').then(() => log('file loaded')).catch((e) => log('load error ' + e.message))
  win.webContents.on('render-process-gone', (_e, d) => log('renderer gone: ' + JSON.stringify(d)))
  win.on('closed', () => log('window closed'))
  setTimeout(() => { log('alive after 5s, windows=' + BrowserWindow.getAllWindows().length); }, 5000)
})
process.on('uncaughtException', (e) => log('uncaught ' + e.message))
process.on('exit', (code) => log('exit ' + code))
